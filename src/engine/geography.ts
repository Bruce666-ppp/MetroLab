export function streetSpacing(area: District) {
  if (area.id === 'oldTown') return 22
  if (area.zone === 'industrial') return 43
  if (area.zone === 'office') return 36
  return area.zone === 'residential' ? 28 : 31
}

export function districtPoint(area: District, u: number, v: number): Point {
  const cos = Math.cos(area.angle)
  const sin = Math.sin(area.angle)
  return { x: area.center.x + u * cos - v * sin, y: area.center.y + u * sin + v * cos }
}

export function districtScore(area: District, point: Point) {
  const dx = point.x - area.center.x
  const dy = point.y - area.center.y
  const cos = Math.cos(area.angle)
  const sin = Math.sin(area.angle)
  return ((dx * cos + dy * sin) / area.radius[0]) ** 2 + ((dy * cos - dx * sin) / area.radius[1]) ** 2
}
